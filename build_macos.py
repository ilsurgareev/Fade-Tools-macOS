"""Build both self-contained Apple Silicon applications with FFmpeg dependencies."""
import os
import hashlib
import subprocess
import sys
from pathlib import Path
from media import tool
from PySide6.QtCore import qVersion
from updater import APP_VERSION

root = Path(__file__).resolve().parent
os.chdir(root)
print('Qt runtime:', qVersion(), flush=True)
expected = {'ffmpeg': '591260c945d0eef150e3bf82b0ef988bd36a9cecc18ff05d6679617159f0a95e',
            'ffprobe': 'e11c17e8200b3ee4c4c186d245e2b4053f01d56957336c1817fca0b997469106'}
for name, digest in expected.items():
    binary = root / 'tools' / name
    if not binary.is_file() or hashlib.sha256(binary.read_bytes()).hexdigest() != digest:
        raise RuntimeError(f'Unexpected bundled {name}; restore the verified tools/ binary')
notices = root / 'bundle-notices'
notices.mkdir(exist_ok=True)
for name in ('ffmpeg', 'ffprobe'):
    (notices / f'{name}-version.txt').write_bytes(subprocess.check_output([tool(name), '-version']))
for label, entry in [('Fade Tools', 'settings_entry.py'), ('Fade Droplet', 'droplet_entry.py')]:
    spec = f'''# Generated by build_macos.py
from pathlib import Path
root = Path(SPECPATH)
a = Analysis([{entry!r}], pathex=[str(root)],
    binaries={[ (tool('ffmpeg'), 'tools'), (tool('ffprobe'), 'tools') ]!r},
    datas=[(str(root / 'THIRD_PARTY.md'), 'licenses'), (str(root / 'third_party_licenses'), 'licenses'), (str(root / 'bundle-notices'), 'licenses')],
    hiddenimports=['updater'], hookspath=[], hooksconfig={{}}, runtime_hooks=[], excludes=[], noarchive=False)
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name={label!r},
    console=False, argv_emulation=False, target_arch='arm64', codesign_identity=None, entitlements_file=None)
coll = COLLECT(exe, a.binaries, a.datas, name={label!r})
app = BUNDLE(coll, name={label + '.app'!r},
    bundle_identifier={'local.fadetools.' + ('droplet' if 'Droplet' in label else 'editor')!r},
    info_plist={{'LSMinimumSystemVersion': '14.4', 'CFBundleShortVersionString': {APP_VERSION!r},
        'CFBundleDocumentTypes': [{{'CFBundleTypeName': 'Video', 'CFBundleTypeRole': 'Editor',
            'LSItemContentTypes': ['public.movie', 'public.audiovisual-content']}}]}})
'''
    path = root / f'{label}.spec'
    path.write_text(spec)
    env = os.environ.copy()
    env['DEVELOPER_DIR'] = '/Library/Developer/CommandLineTools'
    env['PYINSTALLER_CONFIG_DIR'] = str(root / '.pyinstaller-config')
    subprocess.run([sys.executable, '-m', 'PyInstaller', '--noconfirm', '--clean', str(path)], env=env, check=True)
